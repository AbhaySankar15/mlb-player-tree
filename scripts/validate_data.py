"""Independent validation: explicit networkx teammate graph vs. incidence-based results; writes docs/VALIDATION_REPORT.md/.json."""
import itertools, json, os, sys, time
sys.path.insert(0, os.path.dirname(__file__))
import networkx as nx
import export_graph as eg
import normalize_data as nd


def validate(b):
    pl = b["pl"].set_index("playerID")
    checks, t0 = {}, time.time()
    G = nx.Graph()
    G.add_nodes_from(b["p2t"])
    for t, ps in b["t2p"].items():
        G.add_edges_from(itertools.combinations(ps, 2))
    checks["explicit_graph_edges"] = G.number_of_edges()
    checks["no_self_loops"] = nx.number_of_selfloops(G) == 0
    checks["degrees_match_explicit_graph"] = all(G.degree(p) == d for p, d in b["degree"].items())
    ids = set(pl.index)
    checks["every_player_in_graph_once"] = set(b["dist"]) == ids and len(b["dist"]) == len(ids) == len(b["pl"])
    checks["component_count_matches_networkx"] = nx.number_connected_components(G) == len(b["comps"])
    ok_bfs = ok_edge = ok_one_parent = True
    for c, root in zip(b["comps"], b["roots"]):
        sp = nx.single_source_shortest_path_length(G, root)
        ok_bfs &= all(sp[n] == b["dist"][n] for n in c) and len(sp) == len(c)
        edges = [(b["parent"][n], n) for n in c if b["parent"][n] is not None]
        ok_one_parent &= len(edges) == len(c) - 1
        for u, v in edges:
            ok_edge &= G.has_edge(u, v) and b["dist"][v] == b["dist"][u] + 1 and \
                       {b["evid"][v]} <= set(b["p2t"][u]) & set(b["p2t"][v])
        T = nx.Graph(edges); T.add_nodes_from(c)
        ok_one_parent &= nx.is_tree(T)
    checks["bfs_distances_match_networkx"] = bool(ok_bfs)
    checks["tree_edges_are_real_teammate_edges_with_evidence"] = bool(ok_edge)
    checks["each_component_is_tree_N_minus_1_edges"] = bool(ok_one_parent)
    mx = max(b["degree"].values())
    checks["root_has_max_degree"] = b["degree"][b["root"]] == mx
    checks["root_is_smallest_id_among_ties"] = b["root"] == min(p for p, d in b["degree"].items() if d == mx)
    top = sorted(b["degree"], key=lambda p: (-b["degree"][p], p))[:20]
    neg_only = [p for p in pl.index if set(pl.leagues[p].split(",")) <= nd.NEGRO]
    neg_any = [p for p in pl.index if set(pl.leagues[p].split(",")) & nd.NEGRO]
    lg = b["ts"].groupby("leagueId").teamSeasonId.nunique().to_dict()
    mem_by_lg = b["mem"].assign(lg=b["mem"].teamSeasonId.str.split("-").str[1]).groupby("lg").size().to_dict()
    def rep(p):
        return dict(playerId=p, name=pl.fullName[p], years=f"{pl.debutYear[p]}-{pl.finalYear[p]}", leagues=pl.leagues[p],
                    uniqueTeammates=b["degree"][p], depth=b["dist"][p])
    samples = [min(pl.index, key=lambda p: (pl.debutYear[p], p)), max(pl.index, key=lambda p: (pl.finalYear[p], pl.debutYear[p], p))]
    if neg_only:
        samples += [max(neg_only, key=lambda p: (b["degree"][p], p)), min(neg_only, key=lambda p: (pl.debutYear[p], p))]
    if neg_any:
        samples.append(max(set(neg_any) - set(neg_only), key=lambda p: (b["degree"][p], p), default=neg_any[0]))
    people_total = len(b["pl"]) + 0
    return dict(
        checks=checks, allChecksPassed=all(v is True or isinstance(v, int) for v in checks.values()) and
            all(v for k, v in checks.items() if isinstance(v, bool)),
        source=eg.SOURCE_VERSION, years=[int(pl.debutYear.min()), int(pl.finalYear.max())],
        leagues=lg, membershipsByLeague=mem_by_lg, totalPlayers=len(ids), totalTeamSeasons=len(b["ts"]),
        totalMemberships=len(b["mem"]), central=rep(b["root"]), top20=[rep(p) for p in top],
        componentCount=len(b["comps"]), componentSizesTop5=[len(c) for c in b["comps"][:5]],
        largestComponent=len(b["comps"][0]), isolatedPlayers=sum(1 for c in b["comps"] if len(c) == 1),
        maximumSeparation=max(b["dist"].values()),
        negroLeaguesPlayersAny=len(neg_any), negroLeaguesOnlyPlayers=len(neg_only), representativePlayers=[rep(p) for p in samples],
        validationSeconds=round(time.time() - t0, 1),
    )


def write_report(r, md="docs/VALIDATION_REPORT.md", js="docs/validation_report.json"):
    json.dump(r, open(js, "w"), indent=1)
    L = ["# Validation report (machine-generated by scripts/validate_data.py)", "", f"Source: {r['source']}",
         f"Years: {r['years'][0]}-{r['years'][1]}", f"Players: {r['totalPlayers']}  Team-seasons: {r['totalTeamSeasons']}  Memberships: {r['totalMemberships']}",
         f"Components: {r['componentCount']} (largest {r['largestComponent']}, isolated {r['isolatedPlayers']}); max separation {r['maximumSeparation']}",
         f"Central player: {r['central']['name']} ({r['central']['playerId']}), {r['central']['uniqueTeammates']} unique career teammates",
         f"Negro Leagues players (any Negro League season): {r['negroLeaguesPlayersAny']}; Negro-Leagues-only: {r['negroLeaguesOnlyPlayers']}", "",
         "## Checks (explicit networkx graph vs. incidence algorithm)"] + [f"- {'PASS' if v is True else ('FAIL' if v is False else 'INFO')}: {k} = {v}" for k, v in r["checks"].items()]
    L += ["", "## Team-seasons / memberships by league"] + [f"- {k}: {r['leagues'][k]} team-seasons, {r['membershipsByLeague'][k]} memberships" for k in sorted(r["leagues"])]
    L += ["", "## Top 20 by unique career teammates", "| # | Player | Years | Leagues | Teammates |", "|---|---|---|---|---|"]
    L += [f"| {i+1} | {p['name']} ({p['playerId']}) | {p['years']} | {p['leagues']} | {p['uniqueTeammates']} |" for i, p in enumerate(r["top20"])]
    L += ["", "## Representative players (earliest, latest, Negro Leagues)", "| Player | Years | Leagues | Teammates | Depth |", "|---|---|---|---|---|"]
    L += [f"| {p['name']} ({p['playerId']}) | {p['years']} | {p['leagues']} | {p['uniqueTeammates']} | {p['depth']} |" for p in r["representativePlayers"]]
    open(md, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    r = validate(eg.build())
    write_report(r)
    print(json.dumps({k: r[k] for k in ("allChecksPassed", "checks", "negroLeaguesPlayersAny", "validationSeconds")}, indent=1))
    sys.exit(0 if r["allChecksPassed"] else 1)
